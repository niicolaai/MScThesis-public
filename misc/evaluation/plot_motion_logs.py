#!/usr/bin/env python3
"""
Plot motion logs from NPZ files generated by the environment.

Generates visualizations comparing target vs actual motion trajectories.

Usage:
    python plot_motion_logs.py <npz_file>
    python plot_motion_logs.py  # Uses most recent file in current directory
"""

# flake8: noqa: W293

import os
import sys
import glob
import argparse
import numpy as np
import matplotlib.pyplot as plt


def get_time_axis(data_length):
    """Generate time axis in seconds (100 Hz control frequency)."""
    dt = 1.0 / 100.0
    return np.arange(data_length) * dt


def find_latest_npz():
    """Find the most recent NPZ file in the current directory."""
    npz_files = glob.glob('*_env0_motion_log.npz')
    if not npz_files:
        return None
    latest = max(npz_files, key=os.path.getmtime)
    return latest


def plot_joint_angles(data, output_dir, show=False):
    """Plot joint angles comparison."""
    target = data['target_joint_angles']
    actual = data['actual_joint_angles']
    time = get_time_axis(len(target))
    
    joint_labels = [
        'Left Hip Abd', 'Right Hip Abd',
        'Left Hip Flex', 'Right Hip Flex',
        'Left Knee Flex', 'Right Knee Flex',
        'Left Ankle Flex', 'Right Ankle Flex'
    ]
    
    fig, axes = plt.subplots(4, 2, figsize=(14, 12), sharex=True)
    fig.suptitle('Joint Angles: Target vs Actual', fontsize=14, fontweight='bold')
    
    for idx, (ax, label) in enumerate(zip(axes.flatten(), joint_labels)):
        ax.plot(time, target[:, idx], label='Target', linewidth=1.5)
        ax.plot(time, actual[:, idx], label='Actual', linewidth=1.5)
        ax.set_ylabel('Angle (rad)')
        ax.set_title(label, fontsize=10)
        ax.grid(True, alpha=0.3)
        ax.legend()
    
    axes[-1, 0].set_xlabel('Time (s)')
    axes[-1, 1].set_xlabel('Time (s)')
    
    plt.tight_layout()
    if show:
        plt.show()
    else:
        fig.savefig(os.path.join(output_dir, 'joint_angles.png'), dpi=300, bbox_inches='tight')
        print("  Saved: joint_angles.png")
    plt.close(fig)


