def plot_tracking_errors(data, output_dir, show=False):
    """Plot tracking error over time."""
    target_q = data['target_joint_angles']
    actual_q = data['actual_joint_angles']
    target_dq = data['target_joint_velocities']
    actual_dq = data['actual_joint_velocities']
    target_pelvis = data['target_pelvis_position']
    actual_pelvis = data['actual_pelvis_position']
    
    time = get_time_axis(len(target_q))
    
    q_errors = np.sqrt(np.mean((target_q - actual_q)**2, axis=1))
    dq_errors = np.sqrt(np.mean((target_dq - actual_dq)**2, axis=1))
    pelvis_errors = np.sqrt(np.sum((target_pelvis - actual_pelvis)**2, axis=1))
    
    fig, axes = plt.subplots(3, 1, figsize=(12, 9), sharex=True)
    fig.suptitle('Tracking Errors Over Time', fontsize=14, fontweight='bold')
    
    axes[0].plot(time, q_errors, linewidth=1.5)
    axes[0].set_ylabel('Angle Error (rad)')
    axes[0].set_title('Joint Angle Tracking Error')
    axes[0].grid(True, alpha=0.3)
    
    axes[1].plot(time, dq_errors, linewidth=1.5)
    axes[1].set_ylabel('Velocity Error (rad/s)')
    axes[1].set_title('Joint Velocity Tracking Error')
    axes[1].grid(True, alpha=0.3)
    
    axes[2].plot(time, pelvis_errors, linewidth=1.5)
    axes[2].set_ylabel('Position Error (m)')
    axes[2].set_title('Pelvis Position Tracking Error')
    axes[2].grid(True, alpha=0.3)
    
    axes[-1].set_xlabel('Time (s)')
    
    plt.tight_layout()
    if show:
        plt.show()
    else:
        fig.savefig(os.path.join(output_dir, 'tracking_errors.png'), dpi=300, bbox_inches='tight')
        print("  Saved: tracking_errors.png")
    plt.close(fig)


def plot_per_joint_errors(data, output_dir, show=False):
    """Plot per-joint error statistics."""
    target_q = data['target_joint_angles']
    actual_q = data['actual_joint_angles']
    target_dq = data['target_joint_velocities']
    actual_dq = data['actual_joint_velocities']
    
    q_errors = np.sqrt(np.mean((target_q - actual_q)**2, axis=0))
    dq_errors = np.sqrt(np.mean((target_dq - actual_dq)**2, axis=0))
    
    joint_labels = ['L Hip\nAbd', 'R Hip\nAbd', 'L Hip\nFlex', 'R Hip\nFlex',
                   'L Knee\nFlex', 'R Knee\nFlex', 'L Ankle\nFlex', 'R Ankle\nFlex']
    
    fig, axes = plt.subplots(1, 2, figsize=(12, 5))
    fig.suptitle('Per-Joint Error Statistics', fontsize=14, fontweight='bold')
    
    axes[0].bar(range(8), q_errors)
    axes[0].set_ylabel('RMSE (rad)')
    axes[0].set_title('Joint Angle Error')
    axes[0].set_xticks(range(8))
    axes[0].set_xticklabels(joint_labels, fontsize=9)
    axes[0].grid(True, alpha=0.3, axis='y')
    
    axes[1].bar(range(8), dq_errors)
    axes[1].set_ylabel('RMSE (rad/s)')
    axes[1].set_title('Joint Velocity Error')
    axes[1].set_xticks(range(8))
    axes[1].set_xticklabels(joint_labels, fontsize=9)
    axes[1].grid(True, alpha=0.3, axis='y')
    
    plt.tight_layout()
    if show:
        plt.show()
    else:
        fig.savefig(os.path.join(output_dir, 'per_joint_errors.png'), dpi=300, bbox_inches='tight')
        print("  Saved: per_joint_errors.png")
    plt.close(fig)


def main():
    """Main entry point."""
    parser = argparse.ArgumentParser(description='Plot motion logs from NPZ files')
    parser.add_argument('npz_file', nargs='?', default=None, help='Path to NPZ file')
    parser.add_argument('--show', action='store_true', help='Display plots instead of saving')
    args = parser.parse_args()
    
    if args.npz_file is None:
        npz_file = find_latest_npz()
        if npz_file is None:
            print("[ERROR] No NPZ file specified and no *_env0_motion_log.npz files found")
            print(f"[INFO] Current directory: {os.getcwd()}")
            print("[INFO] Usage: python plot_motion_logs.py <npz_file> [--show]")
            sys.exit(1)
        print(f"[INFO] Using latest motion log file: {npz_file}")
    else:
        npz_file = args.npz_file
    
    if not os.path.exists(npz_file):
        print(f"[ERROR] File not found: {npz_file}")
        sys.exit(1)
    
    # Load data
    data = np.load(npz_file)
    print(f"[INFO] Loaded motion logs from: {npz_file}")
    
    # Create output directory
    output_dir = "motion_log_plots"
    if not args.show:
        os.makedirs(output_dir, exist_ok=True)
        print(f"[INFO] Saving plots to: {output_dir}\n")
    else:
        print("[INFO] Displaying plots (not saving)\n")
    
    # Generate plots
    plot_joint_angles(data, output_dir, show=args.show)
    plot_joint_velocities(data, output_dir, show=args.show)
    plot_pelvis_position(data, output_dir, show=args.show)
    plot_pelvis_velocity(data, output_dir, show=args.show)
    plot_tracking_errors(data, output_dir, show=args.show)
    plot_per_joint_errors(data, output_dir, show=args.show)
    
    print("\n[SUCCESS] All plots generated!")


if __name__ == '__main__':
    main()
